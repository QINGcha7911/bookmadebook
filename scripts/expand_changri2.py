#!/usr/bin/env python3
"""讲书稿 v3：章节标题改 ## 号（审稿脚本要求）+ 事实纠错 + 依资料包扩写到 2600+ 字"""
import re
from pathlib import Path

P = Path("bookmadebook-output/讲书稿_长日将尽.txt")
t = P.read_text(encoding="utf-8")

# ---- 1) 章节标题：# → ##（书名行保留单个 #）----
t = re.sub(r"^#\s*(第[一二三四五六七八九十]+章)", r"## \1", t, flags=re.M)
t = re.sub(r"^#\s*(尾声)", r"## \1", t, flags=re.M)

# ---- 2) 事实纠错：养子说的是「勋爵」----
t = t.replace("后来勋爵的养子告诉史蒂文斯：你父亲被人算计了。",
              "后来勋爵的养子告诉史蒂文斯：勋爵被人算计了。")

# ---- 3) 扩写（全部依据资料包确定信息 + 资料包第四节的解读，无臆造）----
REPL = [
 # 第一章：补"尊严"的定义铺垫 + 事后回望
 ("这是他把自己活成了一台机器。",
  "这是他把自己活成了一台机器。\n他给自己的解释是：一位管家，无论何时何地，都应该能坚守他的职业生命。\n这句话他信了一辈子。\n也是这句话，替他挡住了所有他不愿意看见的东西。"),
 # 第二章：补情愫与默契
 ("他把自己锁在\"得体\"里。",
  "他把自己锁在\"得体\"里。\n其实两个人心里都清楚。\n只是谁都不肯先说出来。\n他后来在回忆里反复强调，他们只是工作伙伴。\n可越强调，越像掩饰。"),
 # 第三章：补犹太女仆 + 英王访德
 ("他相信，能通过服务这样一个人，参与改变世界。",
  "他甚至想促成英王去德国，和希特勒见一面。\n史蒂文斯相信他。\n他相信，能通过服务这样一个人，参与改变世界。"),
 ("史蒂文斯这才明白，他奉献了一生的那个信念，可能从头到尾，就是个错。",
  "还有一件事，他很少提。\n勋爵让他解雇两名犹太女仆。\n他照做了，只说了一句：工作职责使然。\n多年以后他才明白，这四个字，也是他给自己找的台阶。\n史蒂文斯这才明白，他奉献了一生的那个信念，可能从头到尾，就是个错。"),
 # 第四章：补旅途的沉默
 ("他一路都在想该怎么开口。\n想了几十年，还是不知道该怎么说。",
  "他一路都在想该怎么开口。\n想了几十年，还是不知道该怎么说。\n他这一辈子，最擅长的就是把话咽回去。\n车窗外是英国最好的季节。\n可他心里翻来覆去，全是三十年前那些没说出口的句子。"),
 # 第五章：补重逢时她的坦白
 ("那一刻，史蒂文斯的心碎了。",
  "她说这句话的时候，很平静。\n反倒比他更勇敢。\n三十年前，他没有回答她。\n三十年后，她替他回答了。\n那一刻，史蒂文斯的心碎了。"),
 # 尾声：补结尾自白那一层
 ("这是他最后的一点念头。",
  "他还说了一句：你我之辈，只要是至少曾为了某项真实而有价值的事业，竭尽绵薄、稍作贡献，谅必就已经够了。\n这句话像安慰，也像他最后一次替自己找理由。\n这是他最后的一点念头。"),
]
for a, b in REPL:
    if a in t:
        t = t.replace(a, b)
    else:
        print("⚠️ 未匹配:", a[:26].replace("\n", "/"))

# ---- 4) 若仍不足，回落点段再补一句主题（资料包第四节解读）----
body = re.sub(r"【[^】]*】", "", t)
if len(re.sub(r"\s", "", body)) < 2600:
    t = t.replace("别等到傍晚，才想起享受人生。",
                  "别等到傍晚，才想起享受人生。\n这本书最锋利的地方，不是它写了一个悲剧。\n是它让我们看见：一个人可以那样体面地，把自己的一生让出去。\n而他自己，到最后都还在替这个决定辩护。")

P.write_text(t, encoding="utf-8")
body = re.sub(r"【[^】]*】", "", t)
print("长度", len(t), "| 正文净字", len(re.sub(r"\s", "", body)))
print("## 章", len(re.findall(r"^##\s*第", t, re.M)), "| ## 尾声", len(re.findall(r"^##\s*尾声", t, re.M)))
print("【金句】", t.count("【金句】"), "【画面】", t.count("【画面"), "【情绪】", t.count("【情绪"))
